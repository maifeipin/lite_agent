"""Todo rendering: thread-safe, process-locked atomic Markdown view generator.
Locks the entire path from reading the latest database snapshot through atomic file replace.
"""

import fcntl
import logging
import os
import tempfile
import threading
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'data')
DEFAULT_MD_PATH = os.path.join(DATA_DIR, 'personal.md')

_render_lock = threading.RLock()


def resolve_md_path(db_path: Optional[str] = None, md_path: Optional[str] = None) -> str:
    if md_path:
        return os.path.abspath(os.path.expanduser(md_path))
    if db_path:
        return os.path.join(os.path.dirname(os.path.abspath(os.path.expanduser(db_path))), 'personal.md')
    return os.path.abspath(DEFAULT_MD_PATH)


def _format_todo(t: Dict[str, Any]) -> str:
    checkbox = "[x]" if t['status'] == 'done' else "[ ]"
    prefix = f"- {checkbox} `{t['id']}`"
    tags = []
    if t.get('kind') and t['kind'] != 'misc':
        tags.append(t['kind'])
    if t.get('project'):
        tags.append(f"proj:{t['project']}")
    tag_str = f" `[{','.join(tags)}]`" if tags else ""

    line = f"{prefix}{tag_str} {t['title']}"

    detail_lines = []
    if t['status'] == 'snoozed' and t.get('snoozed_until'):
        detail_lines.append(f"唤醒时间: {t['snoozed_until']}")
    if t['status'] == 'shelved' and t.get('shelved_reason'):
        detail_lines.append(f"搁置原因: {t['shelved_reason']}")
    if t.get('due_at'):
        detail_lines.append(f"到期时间: {t['due_at']}")
    if t.get('description'):
        detail_lines.append(t['description'])

    if detail_lines:
        detail_str = "\n  ".join(detail_lines)
        line += f"\n  <details><summary>详情</summary>\n\n  {detail_str}\n\n  </details>"
    return line


def render_markdown(db_path: Optional[str] = None, md_path: Optional[str] = None) -> None:
    """Serialize snapshot + replace: locks from DB read to file replace."""
    from features.todo.repository import TodoRepository

    out_md = resolve_md_path(db_path, md_path)
    out_dir = os.path.dirname(out_md)
    os.makedirs(out_dir, exist_ok=True)
    lock_path = out_md + '.lock'

    with _render_lock:
        lock_file = None
        try:
            lock_file = open(lock_path, 'a')
            fcntl.flock(lock_file, fcntl.LOCK_EX)

            repo = TodoRepository(db_path)
            todos = repo.get_active_todos_for_rendering()

            grouped: Dict[str, List[Dict[str, Any]]] = {
                'active': [],
                'pending': [],
                'snoozed': [],
                'shelved': [],
                'done': []
            }
            now_dt = datetime.now(timezone.utc)

            for t in todos:
                st = t['status']
                if st == 'done':
                    comp_dt = datetime.fromisoformat(t['completed_at'].replace('Z', '+00:00')) if t.get('completed_at') else now_dt
                    if (now_dt - comp_dt).days <= 7:
                        grouped['done'].append(t)
                elif st in grouped:
                    grouped[st].append(t)

            lines = [
                "<!-- AUTO-GENERATED by ops_todo. 不要手编，改动会被覆盖。 -->",
                "<!-- 增删改请通过 lite_agent 的飞书或钉钉对话使用 todo_xxx 技能。 -->",
                f"\n# Personal Todos · 最新同步: {datetime.now().strftime('%Y-%m-%d %H:%M')}\n"
            ]

            labels = {
                'active': '进行中',
                'pending': '待办',
                'snoozed': '延期中',
                'shelved': '搁置',
                'done': '已完成（最近 7 天）'
            }

            for k in ['active', 'pending', 'snoozed', 'shelved', 'done']:
                if grouped[k]:
                    lines.append(f"## {labels[k]}\n")
                    for t in grouped[k]:
                        lines.append(_format_todo(t))
                    lines.append("")

            rendered = "\n".join(lines)

            tmp_path = None
            try:
                with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=out_dir, delete=False, suffix=".tmp") as f:
                    f.write(rendered)
                    tmp_path = f.name
                os.replace(tmp_path, out_md)
            finally:
                if tmp_path and os.path.exists(tmp_path):
                    try:
                        os.unlink(tmp_path)
                    except Exception:
                        pass
        except Exception:
            logger.exception("Todo Markdown view refresh failed; database remains authoritative")
        finally:
            if lock_file:
                try:
                    fcntl.flock(lock_file, fcntl.LOCK_UN)
                    lock_file.close()
                except Exception:
                    pass
